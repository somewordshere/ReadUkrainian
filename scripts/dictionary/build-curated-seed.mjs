#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import process from "node:process";

import {
  DICTIONARY_GRAMMAR_TAGS,
  DICTIONARY_PARTS_OF_SPEECH,
} from "../../functions/_shared/dictionary-workflow.js";
import {
  canonicalizeUkrainianWord,
  normalizeUkrainianText,
} from "../../functions/_shared/ukrainian-word.js";

const PROJECT_ROOT = resolve(import.meta.dirname, "../..");
const DEFAULT_SOURCE = resolve(PROJECT_ROOT, "data/dictionary-curated.uk-en.json");
const DEFAULT_OUTPUT = resolve(PROJECT_ROOT, "migrations/0014_dictionary_curated_seed.sql");

function sqlString(value) {
  return `'${String(value ?? "").replaceAll("'", "''")}'`;
}

function hashId(prefix, value) {
  return `${prefix}_${createHash("sha256").update(value, "utf8").digest("hex").slice(0, 24)}`;
}

function parseArgs(argv) {
  const options = { source: DEFAULT_SOURCE, output: DEFAULT_OUTPUT };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    const value = argv[index + 1];
    if (argument === "--source" && value) {
      options.source = resolve(value);
      index += 1;
    } else if (argument === "--output" && value) {
      options.output = resolve(value);
      index += 1;
    } else {
      throw new Error(`Unknown or incomplete option: ${argument}`);
    }
  }
  return options;
}

function validateEntry(entry, index) {
  const lemma = String(entry?.lemma || "").trim().normalize("NFC");
  const normalizedLemma = canonicalizeUkrainianWord(lemma, {
    allowSurroundingPunctuation: false,
  });
  const partOfSpeech = String(entry?.partOfSpeech || "");
  const translation = String(entry?.translation || "").trim();
  if (!normalizedLemma) throw new Error(`Entry ${index + 1} has an invalid lemma.`);
  if (!DICTIONARY_PARTS_OF_SPEECH.includes(partOfSpeech)) {
    throw new Error(`Entry ${index + 1} has an unsupported part of speech.`);
  }
  if (!translation || translation.length > 500) {
    throw new Error(`Entry ${index + 1} has an invalid translation.`);
  }
  if (!Array.isArray(entry.forms) || !entry.forms.length) {
    throw new Error(`Entry ${index + 1} must contain at least one form.`);
  }

  const forms = entry.forms.map((form, formIndex) => {
    const displayForm = normalizeUkrainianText(form?.form);
    const normalizedForm = canonicalizeUkrainianWord(displayForm, {
      allowSurroundingPunctuation: false,
    });
    const tags = [...new Set(Array.isArray(form?.tags) ? form.tags : [])].sort();
    if (!normalizedForm) throw new Error(`Entry ${index + 1}, form ${formIndex + 1} is invalid.`);
    if (tags.some((tag) => !DICTIONARY_GRAMMAR_TAGS.includes(tag))) {
      throw new Error(`Entry ${index + 1}, form ${formIndex + 1} has an unsupported tag.`);
    }
    return { displayForm, normalizedForm, tags };
  });

  return { lemma, normalizedLemma, partOfSpeech, translation, forms };
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  const source = JSON.parse(await readFile(options.source, "utf8"));
  if (!Array.isArray(source.entries)) throw new Error("Curated dictionary entries must be an array.");
  const entries = source.entries.map(validateEntry);
  const lines = [
    "-- Generated by scripts/dictionary/build-curated-seed.mjs.",
    `-- Read Ukrainian reviewed supplement version ${source.version}.`,
    "",
  ];
  const coveredForms = new Set();

  entries.forEach((entry) => {
    const signature = `${entry.normalizedLemma}\u0000${entry.partOfSpeech}\u0000${entry.translation}`;
    const lexemeId = hashId("curated_lex", signature);
    const senseId = hashId("curated_sense", signature);
    lines.push(
      `INSERT OR IGNORE INTO dictionary_lexemes (id, source_language, lemma, normalized_lemma, part_of_speech, source_entry_id, source_id, review_status) VALUES (${sqlString(lexemeId)}, 'uk', ${sqlString(entry.lemma)}, ${sqlString(entry.normalizedLemma)}, ${sqlString(entry.partOfSpeech)}, ${sqlString(`readukrainian-${lexemeId}`)}, 'readukrainian-curated', 'approved');`
    );
    entry.forms.forEach((form) => {
      coveredForms.add(form.normalizedForm);
      lines.push(
        `INSERT OR IGNORE INTO dictionary_forms (lexeme_id, source_language, normalized_form, display_form, tags_json) VALUES (${sqlString(lexemeId)}, 'uk', ${sqlString(form.normalizedForm)}, ${sqlString(form.displayForm)}, ${sqlString(JSON.stringify(form.tags))});`
      );
    });
    lines.push(
      `INSERT OR IGNORE INTO dictionary_senses (id, lexeme_id, sense_order, usage_tags_json) VALUES (${sqlString(senseId)}, ${sqlString(lexemeId)}, 1, '[]');`,
      `INSERT OR IGNORE INTO dictionary_translations (sense_id, target_language, translation, translation_order, source_id, review_status) VALUES (${sqlString(senseId)}, 'en', ${sqlString(entry.translation)}, 1, 'readukrainian-curated', 'approved');`
    );
  });

  lines.push("", "PRAGMA optimize;", "");
  await writeFile(options.output, lines.join("\n"), "utf8");
  process.stdout.write(`${JSON.stringify({
    version: source.version,
    entries: entries.length,
    coveredForms: coveredForms.size,
    output: options.output,
  }, null, 2)}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});
