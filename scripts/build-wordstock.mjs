import fs from "node:fs/promises";
import path from "node:path";

const rootDir = process.cwd();
const seedFile = path.join(rootDir, "data/content-seed.json");

const args = process.argv.slice(2);
function readFlag(name, fallback) {
  const index = args.indexOf(`--${name}`);
  return index === -1 ? fallback : args[index + 1];
}

const level = readFlag("level", "A1").toUpperCase();
const outputFile = path.join(
  rootDir,
  readFlag("out", `prompts/wordstock/${level.toLowerCase()}-wordstock.md`)
);

const PUNCTUATION = /[«»„“”.,!?—–:;()[\]…]/g;

function normalizeWord(word) {
  return word.toLowerCase().replace(PUNCTUATION, "").trim();
}

function toWords(text) {
  return text
    .split(/\s+/)
    .map(normalizeWord)
    .filter((word) => word && /[\p{L}]/u.test(word));
}

function toSentences(text) {
  return text
    .split(/(?<=[.!?…])\s+/)
    .map((sentence) => sentence.trim())
    .filter(Boolean);
}

const seed = JSON.parse(await fs.readFile(seedFile, "utf8"));
const stories = seed
  .filter((story) => story.level === level)
  .sort((left, right) => left.sortOrder - right.sortOrder);

if (stories.length === 0) {
  console.error(`No ${level} stories found in ${path.relative(rootDir, seedFile)}.`);
  process.exit(1);
}

const tokenCount = new Map();
const textCount = new Map();

for (const story of stories) {
  const words = toWords(story.paragraphs.join(" "));
  for (const word of words) {
    tokenCount.set(word, (tokenCount.get(word) ?? 0) + 1);
  }
  for (const word of new Set(words)) {
    textCount.set(word, (textCount.get(word) ?? 0) + 1);
  }
}

const entries = [...tokenCount.entries()]
  .map(([word, tokens]) => ({ word, tokens, texts: textCount.get(word) ?? 0 }))
  .sort((left, right) =>
    right.texts - left.texts || right.tokens - left.tokens || left.word.localeCompare(right.word, "uk")
  );

const seenOnce = entries.filter((entry) => entry.texts === 1);
const established = entries.filter((entry) => entry.texts >= 3);
const totalTokens = entries.reduce((sum, entry) => sum + entry.tokens, 0);

const openings = stories.map((story) => ({
  sortOrder: story.sortOrder,
  title: story.title,
  sentence: toSentences(story.paragraphs[0])[0] ?? "",
}));

const closings = stories.map((story) => {
  const lastParagraph = story.paragraphs[story.paragraphs.length - 1];
  const sentences = toSentences(lastParagraph);
  return {
    sortOrder: story.sortOrder,
    title: story.title,
    sentence: sentences[sentences.length - 1] ?? "",
  };
});

function formatTable(rows) {
  return rows
    .map((entry) => `| ${entry.word} | ${entry.texts} | ${entry.tokens} |`)
    .join("\n");
}

const generatedAt = new Date().toISOString().slice(0, 10);

const document = `# ${level} word stock

Generated by \`scripts/build-wordstock.mjs\` on ${generatedAt}. **Do not edit by
hand** — rerun the script after every batch instead:

\`\`\`sh
npm run wordstock -- --level ${level}
\`\`\`

This file is the input the ${level} story prompt asks for. It carries three
collection-level facts a per-text prompt cannot know on its own: which words the
collection has already taught, which openings are used up, and which closing
moves are used up.

## Summary

| | |
|---|---|
| Texts | ${stories.length} |
| Word tokens | ${totalTokens} |
| Distinct word types | ${entries.length} |
| Types in 3+ texts (established) | ${established.length} (${Math.round((established.length / entries.length) * 100)}%) |
| Types in exactly 1 text (not yet taught) | ${seenOnce.length} (${Math.round((seenOnce.length / entries.length) * 100)}%) |

A learner needs roughly six to eight encounters with a word, spread over time,
to acquire it. The share in the last row is the share of the collection's
vocabulary that no reader will ever consolidate. Bringing it down is the point
of the recycling rule in the prompt.

## Established stock — reuse these freely

Words the collection has already taught, most-established first. New texts
should be built mostly from this list.

| Word | Texts | Tokens |
|---|---|---|
${formatTable(established)}

## Seen once — recycle these next

Words that have appeared in exactly one text. Each new text should pull several
of these forward, so they get a second and third encounter rather than being
dropped.

| Word | Texts | Tokens |
|---|---|---|
${formatTable(seenOnce)}

## Openings already used

Do not reuse these opening moves. The prompt requires a form and position not
used by the neighbouring texts.

${openings.map((entry) => `${entry.sortOrder}. **${entry.title}** — ${entry.sentence}`).join("\n")}

## Closing moves already used

${closings.map((entry) => `${entry.sortOrder}. **${entry.title}** — ${entry.sentence}`).join("\n")}
`;

await fs.mkdir(path.dirname(outputFile), { recursive: true });
await fs.writeFile(outputFile, document, "utf8");

console.log(
  `${level}: ${stories.length} texts, ${entries.length} types, ${seenOnce.length} seen once (${Math.round(
    (seenOnce.length / entries.length) * 100
  )}%).`
);
console.log(`Wrote ${path.relative(rootDir, outputFile)}`);
