#!/usr/bin/env node

// Generate a migration that brings the live texts and questions up to date with
// data/content-seed.json without destroying anything around them.
//
// This exists because 0002_seed_texts.sql and 0005_seed_questions.sql both open
// with an unqualified DELETE, and D1 records migrations by name and never runs
// one twice. Regenerating those two files therefore cannot reach production, and
// re-running them would drop every row: ids, question_index, drafts and editor
// history all go with them, and questions cascade away behind their foreign key.
//
// So this emits upserts instead:
//   - existing rows are matched on the UNIQUE(level, display_order) key and only
//     their content columns are overwritten. is_enabled and question_index are
//     left alone, so a story an editor disabled stays disabled.
//   - missing rows are inserted with question_index = display_order, the
//     convention every live row already follows.
//   - questions are deleted per story, never table-wide, and reinserted.
//   - rows that exist live but not in the seed are never touched or deleted.
//
// Usage:
//   node scripts/build-content-refresh.mjs [--output migrations/00NN_name.sql]

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import process from "node:process";

const PROJECT_ROOT = resolve(import.meta.dirname, "..");
const DEFAULT_OUTPUT = resolve(PROJECT_ROOT, "migrations/0020_content_refresh.sql");

function parseArgs(argv) {
  const options = { output: DEFAULT_OUTPUT };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === "--output" && argv[index + 1]) {
      options.output = resolve(argv[index + 1]);
      index += 1;
    } else {
      throw new Error(`Unknown or incomplete option: ${argv[index]}`);
    }
  }
  return options;
}

function sqlString(value) {
  return `'${String(value ?? "").replaceAll("'", "''")}'`;
}

// The id of a story identified by its natural key, for use inside a statement.
function storyIdSelect(level, order) {
  return `(SELECT id FROM texts WHERE level = ${sqlString(level)} AND display_order = ${order})`;
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  const stories = JSON.parse(await readFile(resolve(PROJECT_ROOT, "data/content-seed.json"), "utf8"));
  const questions = JSON.parse(await readFile(resolve(PROJECT_ROOT, "data/questions-seed.json"), "utf8"));

  const questionsByStory = new Map();
  for (const question of questions) {
    const key = `${question.level}#${question.storyOrder}`;
    if (!questionsByStory.has(key)) questionsByStory.set(key, []);
    questionsByStory.get(key).push(question);
  }

  const lines = [
    "-- Generated by scripts/build-content-refresh.mjs.",
    "-- Brings texts and questions up to date with data/content-seed.json.",
    "--",
    "-- Upserts on UNIQUE(level, display_order). Existing rows keep their id,",
    "-- is_enabled, question_index, drafts and editor history; only the content",
    "-- columns are overwritten. Questions are replaced per story, never with a",
    "-- table-wide DELETE. Rows that exist live but not in the seed are left alone.",
    "-- Re-running this migration is a no-op beyond refreshing updated_at.",
    "",
  ];

  let storyCount = 0;
  let questionCount = 0;

  for (const story of stories) {
    const { level, sortOrder, title, paragraphs, showWordCount } = story;
    const wordCount = showWordCount === false ? 0 : 1;
    const enabled = story.active === false ? 0 : 1;
    storyCount += 1;

    lines.push(
      `INSERT INTO texts (level, display_order, title, paragraphs_json, show_word_count, is_enabled, question_index) ` +
        `VALUES (${sqlString(level)}, ${sortOrder}, ${sqlString(title)}, ${sqlString(JSON.stringify(paragraphs))}, ${wordCount}, ${enabled}, ${sortOrder}) ` +
        `ON CONFLICT(level, display_order) DO UPDATE SET ` +
        `title = excluded.title, paragraphs_json = excluded.paragraphs_json, ` +
        `show_word_count = excluded.show_word_count, updated_at = CURRENT_TIMESTAMP;`
    );

    const storyQuestions = questionsByStory.get(`${level}#${sortOrder}`) || [];
    if (!storyQuestions.length) continue;

    lines.push(`DELETE FROM questions WHERE story_id = ${storyIdSelect(level, sortOrder)};`);
    for (const question of storyQuestions) {
      questionCount += 1;
      lines.push(
        `INSERT INTO questions (story_id, display_order, prompt, correct_answer, wrong_answers_json) ` +
          `VALUES (${storyIdSelect(level, sortOrder)}, ${question.displayOrder}, ${sqlString(question.prompt)}, ` +
          `${sqlString(question.correct)}, ${sqlString(JSON.stringify(question.wrong))});`
      );
    }
  }

  lines.push("");
  await writeFile(options.output, lines.join("\n"), "utf8");
  console.log(JSON.stringify({ stories: storyCount, questions: questionCount, output: options.output }, null, 2));
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
