import fs from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";

const rootDir = process.cwd();
const storyFiles = [
  "js/data/stories.js",
  "js/data/a1-stories.js",
  "js/data/a2-stories.js",
  "js/data/b1-stories.js",
];
const questionFiles = [
  "js/app/questions.js",
  "js/data/a1-questions.js",
  "js/data/a2-questions.js",
  "js/data/b1-questions.js",
];

async function runFiles(files, setupSource, outputExpression, filename) {
  const context = {};
  vm.createContext(context);
  const combinedSourceParts = [setupSource];

  for (const relativeFile of files) {
    const absoluteFile = path.join(rootDir, relativeFile);
    const source = await fs.readFile(absoluteFile, "utf8");
    combinedSourceParts.push(`\n// ${relativeFile}\n${source}`);
  }

  combinedSourceParts.push(`\nglobalThis.__output = ${outputExpression};\n`);
  vm.runInContext(combinedSourceParts.join("\n"), context, { filename });
  return context.__output;
}

function toSqlString(value) {
  return String(value).replace(/'/g, "''");
}

const storiesByLevel = await runFiles(
  storyFiles,
  "",
  "storiesByLevel",
  "stories-bundle.js"
);

const questionDataByLevel = await runFiles(
  questionFiles,
  "",
  "questionDataByLevel",
  "questions-bundle.js"
);

const levels = Object.keys(storiesByLevel || {}).sort();
const storyRecords = [];
const questionRecords = [];

for (const level of levels) {
  const stories = storiesByLevel[level] || [];
  const storyQuestions = questionDataByLevel[level] || [];

  for (const [index, story] of stories.entries()) {
    const sortOrder = index + 1;
    storyRecords.push({
      level,
      sortOrder,
      title: story.title,
      paragraphs: story.paragraphs || [],
      showWordCount: story.showWordCount !== false,
      active: story.active !== false,
    });

    const questions = storyQuestions[index] || [];
    questions.forEach((question, questionIndex) => {
      questionRecords.push({
        level,
        storyOrder: sortOrder,
        displayOrder: questionIndex + 1,
        prompt: question.prompt,
        correct: question.correct,
        wrong: question.wrong || [],
      });
    });
  }
}

const seedDir = path.join(rootDir, "data");
await fs.mkdir(seedDir, { recursive: true });
await fs.writeFile(
  path.join(seedDir, "content-seed.json"),
  `${JSON.stringify(storyRecords, null, 2)}\n`,
  "utf8"
);
await fs.writeFile(
  path.join(seedDir, "questions-seed.json"),
  `${JSON.stringify(questionRecords, null, 2)}\n`,
  "utf8"
);

const textSqlLines = [
  "-- Generated by scripts/build-content-seed.mjs",
  "DELETE FROM texts;",
];

for (const record of storyRecords) {
  const safeLevel = toSqlString(record.level);
  const safeTitle = toSqlString(record.title);
  const safeParagraphs = toSqlString(JSON.stringify(record.paragraphs));

  textSqlLines.push(
    `INSERT INTO texts (level, display_order, title, paragraphs_json, show_word_count, is_enabled) VALUES ('${safeLevel}', ${record.sortOrder}, '${safeTitle}', '${safeParagraphs}', ${record.showWordCount ? 1 : 0}, ${record.active ? 1 : 0});`
  );
}

await fs.writeFile(
  path.join(rootDir, "migrations", "0002_seed_texts.sql"),
  `${textSqlLines.join("\n")}\n`,
  "utf8"
);

const questionSqlLines = [
  "-- Generated by scripts/build-content-seed.mjs",
  "DELETE FROM questions;",
];

for (const record of questionRecords) {
  const safeLevel = toSqlString(record.level);
  const safePrompt = toSqlString(record.prompt);
  const safeCorrect = toSqlString(record.correct);
  const safeWrongAnswers = toSqlString(JSON.stringify(record.wrong));

  questionSqlLines.push(
    `INSERT INTO questions (story_id, display_order, prompt, correct_answer, wrong_answers_json) VALUES ((SELECT id FROM texts WHERE level = '${safeLevel}' AND question_index = ${record.storyOrder} LIMIT 1), ${record.displayOrder}, '${safePrompt}', '${safeCorrect}', '${safeWrongAnswers}');`
  );
}

await fs.writeFile(
  path.join(rootDir, "migrations", "0005_seed_questions.sql"),
  `${questionSqlLines.join("\n")}\n`,
  "utf8"
);

console.log(`Generated ${storyRecords.length} story records and ${questionRecords.length} question records.`);
